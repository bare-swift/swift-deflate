import Testing
@testable import Deflate
import Bytes

private func bytes(_ raw: [UInt8]) -> Bytes {
    var b = Bytes(reservingCapacity: raw.count)
    for x in raw { b.append(x) }
    return b
}

private func string(_ b: Bytes) -> String {
    String(decoding: b.storage, as: UTF8.self)
}

/// All deflate-body byte vectors below were extracted from `gzip -c` output:
/// `printf '...' | gzip -c | xxd` and stripping the 10-byte gzip header
/// + 8-byte trailer.
@Suite("Inflate — fixed Huffman vectors")
struct FixedHuffmanTests {
    @Test("empty deflate body → empty output")
    func empty() throws {
        let result = try Deflate.inflate(bytes([0x03, 0x00]))
        #expect(result.count == 0)
    }

    @Test("'abc' → 'abc'")
    func abc() throws {
        let body: [UInt8] = [0x4B, 0x4C, 0x4A, 0x06, 0x00]
        let result = try Deflate.inflate(bytes(body))
        #expect(string(result) == "abc")
    }

    @Test("'hello world' round-trip")
    func helloWorld() throws {
        let body: [UInt8] = [0xCB, 0x48, 0xCD, 0xC9, 0xC9, 0x57, 0x28, 0xCF, 0x2F, 0xCA, 0x49, 0x01, 0x00]
        let result = try Deflate.inflate(bytes(body))
        #expect(string(result) == "hello world")
    }

    @Test("repeated 'a' compressed via back-references")
    func repeatedA() throws {
        // 'aaaaaaaaaaaaaaaa' (16 bytes) compresses to 5 bytes via length+distance.
        let body: [UInt8] = [0x4B, 0x4C, 0x44, 0x05, 0x00]
        let result = try Deflate.inflate(bytes(body))
        #expect(string(result) == String(repeating: "a", count: 16))
    }
}

@Suite("Inflate — dynamic Huffman vectors")
struct DynamicHuffmanTests {
    /// 'The quick brown fox jumps over the lazy dog. ' × 3.
    /// Long enough to force gzip into a dynamic Huffman block (block type 10).
    @Test("dynamic block with mixed literals + back-references")
    func dynamicBlock() throws {
        let body: [UInt8] = [
            0x0B, 0xC9, 0x48, 0x55, 0x28, 0x2C, 0xCD, 0x4C, 0xCE, 0x56,
            0x48, 0x2A, 0xCA, 0x2F, 0xCF, 0x53, 0x48, 0xCB, 0xAF, 0x50,
            0xC8, 0x2A, 0xCD, 0x2D, 0x28, 0x56, 0xC8, 0x2F, 0x4B, 0x2D,
            0x52, 0x28, 0x01, 0x4A, 0xE7, 0x24, 0x56, 0x55, 0x2A, 0xA4,
            0xE4, 0xA7, 0xEB, 0x29, 0x84, 0xD0, 0x4A, 0x31, 0x00,
        ]
        let result = try Deflate.inflate(bytes(body))
        let exact = "The quick brown fox jumps over the lazy dog. The quick brown fox jumps over the lazy dog. The quick brown fox jumps over the lazy dog."
        #expect(string(result) == exact)
    }
}

@Suite("Inflate — stored blocks")
struct StoredBlockTests {
    @Test("single-byte stored block")
    func storedSingleByte() throws {
        // Construct manually: BFINAL=1, BTYPE=00, align, LEN=1 (LE), NLEN=0xFFFE (LE), payload=0x42.
        // Bits: 1, 00 → byte 0 low 3 bits = 0b001 = 0x01. Padded: 0x01.
        // Then bytes: 01 00 (LEN), FE FF (NLEN), 42 (payload).
        let body: [UInt8] = [0x01, 0x01, 0x00, 0xFE, 0xFF, 0x42]
        let result = try Deflate.inflate(bytes(body))
        #expect(result.count == 1)
        #expect(result.storage[0] == 0x42)
    }

    @Test("stored block length / NLEN mismatch fails")
    func storedBadCheck() {
        let body: [UInt8] = [0x01, 0x01, 0x00, 0x00, 0x00, 0x42]  // NLEN should be 0xFFFE
        #expect(throws: DeflateError.invalidStoredBlockLength) {
            try Deflate.inflate(bytes(body))
        }
    }
}

@Suite("Inflate — error paths")
struct ErrorPathTests {
    @Test("empty input throws .truncated")
    func emptyInput() {
        #expect(throws: DeflateError.truncated) {
            try Deflate.inflate(bytes([]))
        }
    }

    @Test("reserved block type 11 throws")
    func reservedBlock() {
        // BFINAL=1, BTYPE=11. Bits in byte 0 (LSB-first): 1, 1, 1 → 0x07.
        #expect(throws: DeflateError.reservedBlockType) {
            try Deflate.inflate(bytes([0x07]))
        }
    }

    @Test("truncated fixed-Huffman block throws")
    func truncatedFixed() {
        // BFINAL=1, BTYPE=01, but only 1 byte total — Huffman code can't be read.
        #expect(throws: DeflateError.truncated) {
            try Deflate.inflate(bytes([0x03]))
        }
    }
}

